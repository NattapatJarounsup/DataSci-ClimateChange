import pandas as pd
import matplotlib.pyplot as plt

plot_df = flood_df.copy()
plot_df['budget_drainge_dept_val'] = plot_df['budget_drainge_dept (THB)'].astype(str).str.replace(',', '').astype(float)
plot_df['budget_district_office_val'] = plot_df['budget_district_office (THB)'].astype(str).str.replace(',', '').astype(float)
plot_df['total_budget_val'] = plot_df['budget_drainge_dept_val'] + plot_df['budget_district_office_val']

top10_budget_districts = plot_df.nlargest(10, 'total_budget_val')

top10_budget_districts['Drainage Dept (Million THB)'] = top10_budget_districts['budget_drainge_dept_val'] / 1e6
top10_budget_districts['District Office (Million THB)'] = top10_budget_districts['budget_district_office_val'] / 1e6

top10_budget_districts.set_index('district_en')[['Drainage Dept (Million THB)', 'District Office (Million THB)']].plot(
    kind='bar', stacked=True, color=['#1f77b4', '#ff7f0e'], figsize=(12, 6)
)

plt.title('Drainage Dept vs District Office Budget (Top 10 Districts)')
plt.xlabel('District')
plt.ylabel('Budget (Million THB)')
plt.xticks(rotation=45)
plt.legend(['Drainage Dept Budget', 'District Office Budget'])
plt.tight_layout()
plt.show()

plt.figure(figsize=(10, 8))

